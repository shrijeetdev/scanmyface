// Helper: get top 3 products for a given issue
export function getProductsForIssue(issueId, limit = 3) {
  return PRODUCTS
    .filter(p => p.forIssues.includes(issueId))
    .slice(0, limit);
}

// Helper: get all products for multiple issues (deduplicated, max 6)
export function getProductsForIssues(issueIds, limit = 6) {
  const seen = new Set();
  const results = [];
  for (const id of issueIds) {
    for (const p of PRODUCTS) {
      if (p.forIssues.includes(id) && !seen.has(p.id)) {
        seen.add(p.id);
        results.push(p);
        if (results.length >= limit) return results;
      }
    }
  }
  return results;
}
